export function getDict(locale: string | null | undefined): Dict {
  return DICTS[isLocale(locale) ? locale : DEFAULT_LOCALE];
}

/** Replace {placeholders} in a text. */
export function fmt(text: string, values: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

